# função para imprimir valores
def imprimir_dados(texo, numero):
    print(f'Texo: {texo}')
    print(f'Número: {numero}')

# fonecendo valores para função
texto_fornecido = 'Olá, mundo!'
numero_fornecido = 2026

# chamar a função com os valores fornecidos
imprimir_dados(texto_fornecido, numero_fornecido)