#include <stdio.h>

int main(){
    int a = 20;
    int b = 20;

    // vai retorna booleano(0 para false e 1 para true)
    printf("a > b: %d\n", a > b);
    printf("a < b: %d\n", a < b);
    printf("a >= b: %d\n", a >= b);
    printf("a <= b: %d\n", a <= b);
    printf("a == b: %d\n", a == b);
    printf("a != b: %d\n", a != b);

    return 0;
}